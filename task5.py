first_number = 5

first_positive = first_number > 0
first_even = first_number % 2 == 0
first_both = first_positive and first_even

print(f"First number: {first_number}")
print(f"Positive: {first_positive}")
print(f"Even: {first_even}")
print(f"Positive and even: {first_both}")

second_number = 5 * 12

second_positive = second_number > 0
second_even = second_number % 2 == 0
second_both = second_positive and second_even

print(f"Second number: {second_number}")
print(f"Positive: {second_positive}")
print(f"Even: {second_even}")
print(f"Positive and even: {second_both}")
